"""Validate and bake release update public keys into src/_update_keys.py."""

from __future__ import annotations

import base64
import json
import os
from pathlib import Path


def main() -> None:
    raw = os.environ.get("LULLMAIL_UPDATE_PUBLIC_KEYS", "").strip()
    required = os.environ.get("LULLMAIL_REQUIRE_SIGNED_UPDATES") == "1"
    if not raw:
        if required:
            raise SystemExit("LULLMAIL_UPDATE_PUBLIC_KEYS is required for a signed release build")
        keys: dict[str, str] = {}
    else:
        parsed = json.loads(raw)
        if not isinstance(parsed, dict) or not parsed:
            raise SystemExit("LULLMAIL_UPDATE_PUBLIC_KEYS must be a non-empty JSON object")
        keys = {}
        for key_id, encoded in parsed.items():
            if not isinstance(key_id, str) or not key_id.strip():
                raise SystemExit("Every update key needs a non-empty string key_id")
            if not isinstance(encoded, str):
                raise SystemExit(f"Update key {key_id!r} must be Base64 text")
            try:
                decoded = base64.b64decode(encoded, validate=True)
            except Exception as exc:
                raise SystemExit(f"Update key {key_id!r} is not valid Base64: {exc}") from exc
            if len(decoded) != 32:
                raise SystemExit(f"Update key {key_id!r} must decode to 32 bytes")
            keys[key_id] = encoded

    target = Path(__file__).resolve().parents[1] / "src" / "_update_keys.py"
    target.write_text(
        "# Generated by scripts/embed_update_keys.py; do not commit.\n"
        f"TRUSTED_UPDATE_KEYS = {keys!r}\n",
        encoding="utf-8",
    )
    print(f"Embedded {len(keys)} trusted update key(s) in {target}")


if __name__ == "__main__":
    main()
