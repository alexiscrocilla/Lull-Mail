function detectLocale() {
  try {
    const url = new URL(window.location.href);
    const q = url.searchParams.get('lang');
    if (q === 'en' || q === 'fr') return q;
    const stored = localStorage.getItem('lullmail.lang');
    if (stored === 'en' || stored === 'fr') return stored;
  } catch (_) { /* ignore (file://, sandbox, …) */ }
  const nav = (navigator.language || navigator.userLanguage || 'fr').toLowerCase();
  // FR-first app: only switch to English when the system explicitly asks
  // for it. Any other locale (de, es, it, …) gets French — consistent
  // with the screens that haven't been i18n'd yet.
  return nav.startsWith('en') ? 'en' : 'fr';
}

const LOCALE = detectLocale();

function t(key, vars) {
  let s = (STRINGS[LOCALE] && STRINGS[LOCALE][key]) || STRINGS.en[key] || key;
  if (vars) {
    for (const k of Object.keys(vars)) {
      s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
    }
  }
  return s;
}

function applyI18n(root) {
  const r = root || document;
  r.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  r.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  r.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  r.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
    el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel));
  });
  r.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.setAttribute('title', t(el.dataset.i18nTitle));
  });
}

window.t = t;
window.applyI18n = applyI18n;
window.LULLMAIL_LOCALE = LOCALE;

document.documentElement.lang = LOCALE;

// ── Accept-Language injection ─────────────────────────────────────────────
// The backend reads this header (`src/i18n.py:get_locale`) to return
// translated error messages, toasts, and validation feedback. We patch
// window.fetch so every /api/* call carries the locale without the
// caller having to remember — the backend default falls back to French.
(function injectLocaleHeader() {
  const orig = window.fetch.bind(window);
  window.fetch = function (input, init) {
    init = init || {};
    const url = typeof input === 'string'
      ? input
      : (input && input.url) || '';
    if (url.startsWith('/api/')) {
      const headers = new Headers(init.headers || undefined);
      if (!headers.has('Accept-Language')) {
        headers.set('Accept-Language', LOCALE);
      }
      init = { ...init, headers };
    }
    return orig(input, init);
  };
})();

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => applyI18n());
} else {
  applyI18n();
}
